/**
 * Marks the page with the language on show: the phone then picks a Devanagari font for Hindi, and the style sheet
 * sets Hindi a little smaller than English so the two look the same size. `restore` is put back when the screen goes.
 */
export function usePageLanguage(language: Settings['language'], restore: Settings['language'] = language) {
  useEffect(() => {
    document.documentElement.lang = language
    return () => { document.documentElement.lang = restore }
  }, [language, restore])
}

